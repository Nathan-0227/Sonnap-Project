/// 補填某一個**過去的**夜晚。
///
/// ═══════════════════════════════════════════════════════════════════
/// 為什麼需要這個
/// ═══════════════════════════════════════════════════════════════════
/// 上傳只在 Insights 頁那一輪做，而 `lightsOut()` 的視窗是「從**現在**
/// 往回 24 小時」。所以連續兩天沒開 App，中間那一晚就永遠上傳不到——
/// 不是資料沒了（Android 自己的事件保留 ≥5 天），是沒有東西去撈它。
///
/// 2026-09-09 就是這樣：手機本機留著那晚的上床標記、Android 留著事件流，
/// 但 `nightly_behavior` 連一列都沒有。
///
/// ⚠️ **D2 受測者忘記開 App 是常態不是例外**，所以這條路要留著。
///
/// ═══════════════════════════════════════════════════════════════════
/// ⚠️ 用的是同一條程式路徑
/// ═══════════════════════════════════════════════════════════════════
/// 這裡**只換 `now`**，其餘完全走 `lightsOut()` → `detectLightsOut()`。
/// 不另外寫一份「補填用」的偵測邏輯——那會是第二個定義處，而兩份漂移時
/// 不會有任何錯誤訊息（這個專案已經因為同型的問題吃過好幾次虧）。
///
/// ═══════════════════════════════════════════════════════════════════
/// ⚠️ 開著的時候畫面上一定要看得出來
/// ═══════════════════════════════════════════════════════════════════
/// 最危險的情況不是補填失敗，是**有人用補填版的 APK 當日常版在用**——
/// 那樣每天上傳的都是同一個過去的夜晚，而畫面看起來完全正常。
/// 所以 [isActive] 為真時，Insights 頁必須顯示明顯的橫幅。
/// `report_screen_test.dart` 有一條守著。
library;

/// 建置時指定要補填的時刻（ISO8601）。留空 = 正常運作。
///
///     flutter build apk --debug \
///       --dart-define=SONNAP_BACKFILL_NOW=2026-09-09T12:00:00
///
/// 給的是「假裝現在是這個時刻」，不是那一晚的日期——因為 `lightsOut()`
/// 的視窗是往回 24 小時。要補 09-09 那一夜（凌晨上床、早上起床），
/// 就給 09-09 中午：視窗涵蓋 09-08 12:00 ~ 09-09 12:00，那段安靜期整段在內。
const String kBackfillNowRaw =
    String.fromEnvironment('SONNAP_BACKFILL_NOW', defaultValue: '');

/// 解析後的補填時刻。沒給或格式不對就是 null（**不是**丟例外——
/// 打錯字不該讓整個 App 開不起來，但也不該安靜地變成正常模式，
/// 所以 [isMisconfigured] 分得出這兩種）。
DateTime? get backfillNow =>
    kBackfillNowRaw.isEmpty ? null : DateTime.tryParse(kBackfillNowRaw);

/// 有在補填模式。
bool get isActive => backfillNow != null;

/// 給了值但解析不出來——這要讓人看到，不能當成沒給。
bool get isMisconfigured => kBackfillNowRaw.isNotEmpty && backfillNow == null;
